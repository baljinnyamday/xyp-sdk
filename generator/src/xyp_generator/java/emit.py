"""Render the Java SDK's generated sources from the IR."""

from __future__ import annotations

import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

from jinja2 import Environment, PackageLoader, StrictUndefined

from xyp_generator.ir import Api, Field, Service, TypeRef
from xyp_generator.java.names import (
    JAVA_KEYWORDS,
    OBJECT_METHODS,
    decapitalize,
    group_accessor_name,
    group_class_name,
    is_identifier,
    java_field_name,
    java_package_name,
    java_string,
    java_type_name,
    javadoc,
    upper_first,
)
from xyp_generator.naming import split_operation

# The same line as the Go SDK. Tools that look for generated Java (the
# `@Generated` annotation aside) match this comment, and the emitter trusts it
# when it deletes the packages of a previous run.
HEADER = "// Code generated by xyp-generator from spec/services.json. DO NOT EDIT."

ROOT_PACKAGE = "io.github.baljinnyamday.xyp"
SOURCE_ROOT = PurePosixPath("src", "main", "java")

_CORE = f"{ROOT_PACKAGE}."

# Kind -> (Java type, Decoders constant). The boxed types are on purpose: 0 and
# false are real answers from XYP, so null is the only honest way to say absent.
_SCALARS: dict[str, tuple[str, str]] = {
    "string": ("String", "STRING"),
    "int": ("Long", "INT"),
    "float": ("Double", "FLOAT"),
    "bool": ("Boolean", "BOOL"),
    "decimal": ("BigDecimal", "DECIMAL"),
    "bytes": ("byte[]", "BYTES"),
    "date": ("XypDate", "DATE"),
    "any": ("Object", "ANY"),
}
_SCALAR_IMPORTS = {"decimal": "java.math.BigDecimal", "date": f"{_CORE}XypDate"}

# Every simple type name a generated file refers to without qualifying it. A
# nested record with one of these names would shadow it for the whole file (a
# record `List` makes `List<List>` unreadable and uncompilable), and a top-level
# type with one would clash with its own import.
_REFERENCED_TYPES = frozenset(
    {
        "BigDecimal", "Boolean", "CallOptions", "Decoders", "Double", "Extras", "List",
        "Long", "Map", "Object", "Objects", "Override", "Params", "Record",
        "RequestParams", "ResponseReader", "String", "XypApiException", "XypClient",
        "XypDate", "XypException",
    }
)  # fmt: skip

_EXTRAS = "extras"
# The Params class declares these methods itself (and its builder `build()`), so a
# field with one of these names would clash with or overload them.
_PARAMS_MEMBERS = frozenset({"builder", "build", "toParams"})
# What XypClient declares next to the group accessors XypGroups gives it.
_CLIENT_MEMBERS = frozenset({"builder", "call", "close", "invoke"}) | OBJECT_METHODS
# A constructor takes at most 255 parameter slots, one of them `this`.
_MAX_COMPONENTS = 254

_NESTED_SUFFIX = {"list": "Item", "object": "Value"}
# What the Params builder needs to copy a mutable argument.
_COPY_IMPORTS: dict[str, frozenset[str]] = {
    "list": frozenset({"java.util.ArrayList", "java.util.Collections"}),
    "map": frozenset({"java.util.Collections", "java.util.LinkedHashMap"}),
}


@dataclass(frozen=True)
class ComponentView:
    name: str
    wire_name: str
    type: str
    decoder: str  # expression that reads the component in decode()


@dataclass(frozen=True)
class RecordView:
    name: str
    javadoc: tuple[str, ...]
    components: tuple[ComponentView, ...]
    records: tuple[RecordView, ...]  # nested records, in field order


@dataclass(frozen=True)
class ParamView:
    name: str
    wire_name: str
    type: str
    copy: str  # "array", "list", "map" or "" for an immutable value
    doc: str


@dataclass(frozen=True)
class ParamsView:
    name: str
    fields: tuple[ParamView, ...]
    imports: tuple[str, ...]


@dataclass(frozen=True)
class ResponseView:
    record: RecordView
    imports: tuple[str, ...]

    @property
    def name(self) -> str:
        return self.record.name


@dataclass(frozen=True)
class MethodView:
    javadoc: tuple[str, ...]
    parameters: str
    body: str


@dataclass(frozen=True)
class OperationView:
    method: str  # e.g. "getCitizenIDCardInfo"
    operation: str  # e.g. "WS100101_getCitizenIDCardInfo"
    params: ParamsView | None
    response: ResponseView | None
    overloads: tuple[MethodView, ...]

    @property
    def return_type(self) -> str:
        return self.response.name if self.response else "Object"

    @property
    def type_names(self) -> tuple[str, ...]:
        """The top-level types this operation adds to its group's package."""
        names = (self.params and self.params.name, self.response and self.response.name)
        return tuple(sorted(name for name in names if name))


@dataclass(frozen=True)
class GroupView:
    name: str  # "labor_welfare"
    package: str  # "io.github.baljinnyamday.xyp.laborwelfare"
    class_name: str  # "LaborWelfareClient"
    accessor: str  # "laborWelfare"
    endpoints: tuple[str, ...]
    operations: tuple[OperationView, ...]

    @property
    def directory(self) -> PurePosixPath:
        return SOURCE_ROOT.joinpath(*self.package.split("."))

    @property
    def summary(self) -> str:
        """'the 6 XYP services of the {@code meta} group, served from {@code meta-1.5.0}'."""
        endpoints = ", ".join(f"{{@code {endpoint}}}" for endpoint in self.endpoints)
        count = len(self.operations)
        noun = "service" if count == 1 else "services"
        return f"the {count} XYP {noun} of the {{@code {self.name}}} group, served from {endpoints}"


def _sentence(text: str) -> str:
    return text if not text or text[-1] in ".!?" else f"{text}."


def _require_unique(owner: str, kind: str, names: list[str], *, fold_case: bool = False) -> None:
    """Two wire names can spell the same Java name ('civil_id' and 'civilId'). No
    rule can pick a winner, so the generator stops and the catalog gets looked at."""
    keys = [name.lower() if fold_case else name for name in names]
    duplicates = sorted(
        {name for name, key in zip(names, keys, strict=True) if keys.count(key) > 1}
    )
    if duplicates:
        raise ValueError(f"Java {owner} would declare these {kind} twice: {duplicates}")


def _fresh_type_name(field: Field, taken: frozenset[str]) -> str:
    """PascalCase(wire name), unless a type it would clash with already owns that
    name case-insensitively: an enclosing type (JLS 8.1 forbids the same name), a
    sibling (class files differ only in case on case-insensitive disks), or a type
    the file uses. Then 'Item' is appended for a list element, 'Value' for a
    single object, and a counter from 2 on if that is taken too."""
    base = java_type_name(field.wire_name)
    if base.lower() not in taken:
        return base
    suffixed = f"{base}{_NESTED_SUFFIX[field.type.kind]}"
    candidates = (suffixed, *(f"{suffixed}{n}" for n in range(2, len(taken) + 3)))
    return next(name for name in candidates if name.lower() not in taken)


def _scalar_imports(kind: str) -> frozenset[str]:
    found = _SCALAR_IMPORTS.get(kind)
    return frozenset({found}) if found else frozenset()


def _is_object(type_ref: TypeRef) -> bool:
    item = type_ref.item if type_ref.kind == "list" else None
    return type_ref.kind == "object" or (item is not None and item.kind == "object")


def _output_type(type_ref: TypeRef, nested: str) -> tuple[str, str, frozenset[str]]:
    """(Java type, Decoders expression, imports) of a response field; `nested` is
    the record an object decodes into."""
    if type_ref.kind == "list" and type_ref.item:
        item, decoder, imports = _output_type(type_ref.item, nested)
        return f"List<{item}>", f"Decoders.list({decoder})", imports | {"java.util.List"}
    if type_ref.kind == "object":
        return nested, f"Decoders.object({nested}::decode)", frozenset()
    java_type, constant = _SCALARS[type_ref.kind]
    return java_type, f"Decoders.{constant}", _scalar_imports(type_ref.kind)


def _record(
    name: str,
    summary: str,
    fields: tuple[Field, ...],
    enclosing: frozenset[str],
    *,
    operation: str,
    root: bool,
) -> tuple[RecordView, frozenset[str]]:
    """One response record and, depth-first, the records nested in it. `enclosing`
    holds (lower-cased) the type names a nested record must not take."""
    reserved: frozenset[str] = frozenset({_EXTRAS}) if root else frozenset()
    inner = enclosing | {name.lower()}
    taken = inner
    components: tuple[ComponentView, ...] = ()
    records: tuple[RecordView, ...] = ()
    params: tuple[str, ...] = ()
    imports: frozenset[str] = frozenset()
    for field in fields:
        component = java_field_name(field.wire_name, reserved)
        nested_name = ""
        if _is_object(field.type):
            nested_name = _fresh_type_name(field, taken)
            taken = taken | {nested_name.lower()}
            nested, nested_imports = _record(
                nested_name,
                _nested_summary(field, operation),
                field.children,
                inner,
                operation=operation,
                root=False,
            )
            records = (*records, nested)
            imports = imports | nested_imports
        java_type, decoder, type_imports = _output_type(field.type, nested_name)
        imports = imports | type_imports
        components = (
            *components,
            ComponentView(
                name=component,
                wire_name=field.wire_name,
                type=java_type,
                decoder=f"reader.get({java_string(field.wire_name)}, {decoder})",
            ),
        )
        # Every component gets a tag, so the Javadoc passes doclint's "missing" group too.
        doc = javadoc(field.doc) or f"the {{@code {field.wire_name}}} field"
        params = (*params, f"@param {component} {doc}")
    if root:
        components = (*components, ComponentView(_EXTRAS, "", "Extras", "reader.extras()"))
        params = (
            *params,
            f"@param {_EXTRAS} the response fields that did not fit this record (their component"
            " is {@code null} or empty) and the raw response, including the fields this record"
            " does not declare",
        )
    _require_unique(f"record {name!r}", "components", [c.name for c in components])
    if len(components) > _MAX_COMPONENTS:
        raise ValueError(f"Java record {name!r} would have more components than Java allows")
    lines = (summary, "", *params)
    return RecordView(name, lines, components, records), imports


def _nested_summary(field: Field, operation: str) -> str:
    doc = javadoc(field.doc)
    if doc:
        return _sentence(doc)
    what = "An element of the" if field.type.kind == "list" else "The"
    kind = "list" if field.type.kind == "list" else "object"
    return f"{what} {{@code {field.wire_name}}} {kind} in the response of {{@code {operation}}}."


def _response_view(service: Service, base: str) -> ResponseView:
    doc = javadoc(service.doc)
    summary = f"The response of {{@code {service.operation}}}" + (f": {doc}" if doc else "")
    record, imports = _record(
        f"{base}Response",
        _sentence(summary),
        service.outputs,
        frozenset(name.lower() for name in _REFERENCED_TYPES),
        operation=service.operation,
        root=True,
    )
    lines = (
        record.javadoc[0],
        "",
        "<p>A field XYP left out, or sent in a shape this record does not expect, is {@code null}"
        " (an empty list for a list); {@link #extras()} tells the two apart.",
        *record.javadoc[1:],
    )
    core = {f"{_CORE}Decoders", f"{_CORE}Extras", f"{_CORE}ResponseReader"}
    return ResponseView(
        RecordView(record.name, lines, record.components, record.records),
        tuple(sorted(imports | core)),
    )


def _input_type(type_ref: TypeRef) -> tuple[str, frozenset[str]]:
    if type_ref.kind == "list" and type_ref.item:
        item, imports = _input_type(type_ref.item)
        return f"List<{item}>", imports | {"java.util.List"}
    if type_ref.kind == "object":
        return "Map<String, Object>", frozenset({"java.util.Map"})
    return _SCALARS[type_ref.kind][0], _scalar_imports(type_ref.kind)


def _params_view(service: Service, base: str) -> ParamsView:
    fields: tuple[ParamView, ...] = ()
    imports = frozenset({f"{_CORE}Params", f"{_CORE}RequestParams"})
    for field in service.inputs:
        java_type, type_imports = _input_type(field.type)
        copy = {"bytes": "array", "list": "list", "object": "map"}.get(field.type.kind, "")
        copy_imports = _COPY_IMPORTS.get(copy, frozenset())
        imports = imports | type_imports | copy_imports
        fields = (
            *fields,
            ParamView(
                name=java_field_name(field.wire_name, _PARAMS_MEMBERS),
                wire_name=field.wire_name,
                type=java_type,
                copy=copy,
                doc=_sentence(javadoc(field.doc)),
            ),
        )
    view = ParamsView(f"{base}Params", fields, tuple(sorted(imports)))
    _require_unique(f"class {view.name!r}", "fields", [field.name for field in fields])
    return view


def _overloads(
    service: Service,
    method: str,
    params: ParamsView | None,
    response: ResponseView | None,
) -> tuple[MethodView, ...]:
    doc = javadoc(service.doc)
    organization = javadoc(service.organization)
    head = (
        _sentence(f"Calls {{@code {service.operation}}}" + (f": {doc}" if doc else "")),
        *(("", f"<p>Provider: {_sentence(organization)}") if organization else ()),
        "",
    )
    param_line = ("@param params the request fields; {@code null} sends none",) if params else ()
    returns = (
        "@return the decoded response"
        if response
        else "@return the response as a tree: maps in document order, lists for repeated"
        " elements, and strings"
    )
    throws = (
        "@throws XypApiException if XYP answers with a non-zero result code",
        "@throws XypException if the call fails for any other reason: configuration,"
        " network, or a response that is not the expected SOAP",
    )
    typed = f"{params.name} params" if params else ""
    argument = "params" if params else "null"
    target = (
        f"client.invoke({java_string(service.operation)}, {argument}, {{options}},"
        f" {response.name}::decode)"
        if response
        else f"client.call({java_string(service.operation)}, {argument}, {{options}})"
    )
    if not service.accepts_auth:
        return (
            MethodView(
                (*head, *param_line, returns, *throws),
                typed,
                target.format(options="CallOptions.none()"),
            ),
        )
    with_options = ", ".join(item for item in (typed, "CallOptions options") if item)
    delegate = ", ".join(
        item for item in ("params" if params else "", "CallOptions.none()") if item
    )
    options_line = (
        "@param options the citizen's and the operator's authentication, or an endpoint"
        " override; {@link CallOptions#none()} for none"
    )
    return (
        MethodView((*head, *param_line, returns, *throws), typed, f"{method}({delegate})"),
        MethodView(
            (*head, *param_line, options_line, returns, *throws),
            with_options,
            target.format(options="options"),
        ),
    )


def _operation_view(service: Service, method: str, base: str) -> OperationView:
    params = _params_view(service, base) if service.inputs else None
    response = _response_view(service, base) if service.outputs else None
    return OperationView(
        method=method,
        operation=service.operation,
        params=params,
        response=response,
        overloads=_overloads(service, method, params, response),
    )


def _group_view(group: str, services: tuple[Service, ...]) -> GroupView:
    """Names only have to be unique inside the group's package, which is the only
    place they are visible. The rules are the Go SDK's, compared case-insensitively
    because Java class files share a directory on case-insensitive disks."""
    class_name = group_class_name(group)
    reserved_types = {name.lower() for name in {*_REFERENCED_TYPES, class_name}}
    operations: tuple[OperationView, ...] = ()
    for service in services:
        code, short = split_operation(service.operation)
        if not is_identifier(short):
            raise ValueError(f"{service.operation} does not make a Java method name")
        taken: set[str] = {operation.method.lower() for operation in operations}
        base = upper_first(short)
        base = f"{base}{code}" if base.lower() in taken else base
        method = decapitalize(base)
        if method in JAVA_KEYWORDS or method in OBJECT_METHODS:
            method = f"{method}{code}"
        view = _operation_view(service, method, base)
        used = reserved_types | {
            name.lower() for operation in operations for name in operation.type_names
        }
        if used & {name.lower() for name in view.type_names}:
            # The same service published twice: keep the method name, qualify the types.
            view = _operation_view(service, method, f"{base}{code}")
        operations = (*operations, view)

    result = GroupView(
        name=group,
        package=f"{ROOT_PACKAGE}.{java_package_name(group)}",
        class_name=class_name,
        accessor=group_accessor_name(group),
        endpoints=tuple(sorted({service.endpoint for service in services})),
        operations=operations,
    )
    owner = f"package {result.package!r}"
    _require_unique(owner, "methods", [op.method for op in operations], fold_case=True)
    types = [class_name, *(name for op in operations for name in op.type_names)]
    _require_unique(owner, "types", types, fold_case=True)
    return result


def _group_views(api: Api) -> tuple[GroupView, ...]:
    groups = tuple(_group_view(name, services) for name, services in api.groups.items())
    _require_unique("module", "packages", [group.package for group in groups], fold_case=True)
    accessors = [group.accessor for group in groups]
    _require_unique("class 'XypGroups'", "methods", accessors, fold_case=True)
    clashing = sorted(set(accessors) & _CLIENT_MEMBERS)
    if clashing:
        raise ValueError(f"Group accessors would clash with XypClient's own methods: {clashing}")
    return groups


def _javadoc_block(lines: tuple[str, ...]) -> str:
    """Lines are escaped already; this is the last guard before javac sees them."""
    for line in lines:
        if "*/" in line or "\\" in line or "\n" in line:
            raise ValueError(f"Unsafe Javadoc line: {line!r}")
    body = "\n".join(f" * {line}" if line else " *" for line in lines)
    return f"/**\n{body}\n */"


def _environment() -> Environment:
    environment = Environment(
        loader=PackageLoader("xyp_generator.java", "templates"),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )
    environment.filters["javadoc"] = _javadoc_block
    environment.filters["javastr"] = java_string
    return environment


def emit(api: Api, package_dir: Path, *, format: bool = True) -> list[Path]:
    """Write every generated file into `package_dir` (…/packages/java) and format them.

    `format=False` skips google-java-format, for tests that have no Maven project.
    """
    mvnw = package_dir / "mvnw"
    if format and not mvnw.is_file():
        raise FileNotFoundError(
            f"{mvnw} is missing: the Java sources are formatted with `./mvnw spotless:apply`"
            " from the Maven project (pass format=False to skip formatting)"
        )
    environment = _environment()

    def render(template: str, **context: object) -> str:
        template_context = {"header": HEADER, "root_package": ROOT_PACKAGE, **context}
        return environment.get_template(template).render(**template_context)

    groups = _group_views(api)
    core = SOURCE_ROOT.joinpath(*ROOT_PACKAGE.split("."))
    outputs: tuple[tuple[PurePosixPath, str], ...] = (
        (SOURCE_ROOT / "module-info.java", render("module-info.java.j2", groups=groups)),
        (
            core / "Registry.java",
            render(
                "Registry.java.j2",
                # Sorted, so the file only changes when the catalog does.
                operation_endpoints=sorted((s.operation, s.endpoint) for s in api.services),
                known_namespaces=sorted(api.namespaces.items()),
            ),
        ),
        (core / "XypGroups.java", render("XypGroups.java.j2", groups=groups)),
    )
    for group in groups:
        directory = group.directory
        outputs = (
            *outputs,
            (directory / "package-info.java", render("package-info.java.j2", group=group)),
            (
                directory / f"{group.class_name}.java",
                render("Client.java.j2", group=group),
            ),
        )
        for operation in group.operations:
            if operation.params:
                outputs = (
                    *outputs,
                    (
                        directory / f"{operation.params.name}.java",
                        render(
                            "Params.java.j2",
                            group=group,
                            operation=operation,
                            params=operation.params,
                        ),
                    ),
                )
            if operation.response:
                outputs = (
                    *outputs,
                    (
                        directory / f"{operation.response.name}.java",
                        render("Response.java.j2", group=group, response=operation.response),
                    ),
                )
    relative = [path for path, _ in outputs]
    _require_unique("sources", "files", [str(path) for path in relative], fold_case=True)

    _remove_stale_packages(package_dir / core)
    paths = [package_dir / path for path in relative]
    for path, (_, content) in zip(paths, outputs, strict=True):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    if format:
        _format(package_dir)
    return paths


def _remove_stale_packages(core: Path) -> None:
    """Drop the group packages of a previous run, so a group XYP removed does not
    linger. A directory counts as generated only when its client class carries the
    header, so hand-written packages next to them are never touched."""
    if not core.is_dir():
        return
    for directory in sorted(core.iterdir()):
        if not directory.is_dir():
            continue
        clients = sorted(directory.glob("*Client.java"))
        if any(path.read_text(encoding="utf-8").startswith(HEADER) for path in clients):
            shutil.rmtree(directory)


def _format(package_dir: Path) -> None:
    # google-java-format through Spotless, the same step CI checks with spotless:check.
    subprocess.run(["./mvnw", "-q", "-B", "spotless:apply"], cwd=package_dir, check=True)
