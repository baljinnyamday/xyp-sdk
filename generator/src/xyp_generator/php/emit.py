"""Render the PHP SDK's generated classes from the IR."""

from __future__ import annotations

import shutil
import subprocess
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path

from jinja2 import Environment, PackageLoader, StrictUndefined

from xyp_generator.ir import Api, Field, Service, TypeRef
from xyp_generator.naming import split_operation
from xyp_generator.php.names import (
    RESERVED_CLASS_NAMES,
    class_part,
    group_namespace,
    group_property,
    method_name,
    property_name,
    upper_first,
)

# Placed right after `declare(strict_types=1);` in every generated file. The Go
# wording, which tools and reviewers already recognise as "generated, hands off".
HEADER = "// Code generated by xyp-generator from spec/services.json. DO NOT EDIT."
PREAMBLE = f"<?php\n\ndeclare(strict_types=1);\n\n{HEADER}\n"
ROOT_NAMESPACE = "Xyp"
# How far into a file the header may sit and still mark it as generated.
_HEADER_LINES = 5

_AUTH = "Xyp\\Auth"
_CLIENT = "Xyp\\XypClient"
_DATE = "Xyp\\Date"
_EXTRAS = "Xyp\\Extras"
_BYTES_ATTRIBUTE = "Xyp\\Attribute\\Bytes"
_DECIMAL_ATTRIBUTE = "Xyp\\Attribute\\Decimal"
_LIST_OF_ATTRIBUTE = "Xyp\\Attribute\\ListOf"
_WIRE_ATTRIBUTE = "Xyp\\Attribute\\Wire"
# Every short name a generated file may import. A generated class of the same name
# in the group's namespace would be shadowed by the import, so none may exist.
_IMPORTED_NAMES = frozenset(
    name.rsplit("\\", 1)[-1].lower()
    for name in (
        _AUTH,
        _CLIENT,
        _DATE,
        _EXTRAS,
        _BYTES_ATTRIBUTE,
        _DECIMAL_ATTRIBUTE,
        _LIST_OF_ATTRIBUTE,
        _WIRE_ATTRIBUTE,
    )
)

_EXTRAS_PROPERTY = "xyp"
_THROWS = "@throws \\Xyp\\Exception\\XypException"
_SENTENCE_END = (".", "!", "?")

# PHP type (native, phpdoc) per scalar kind. Scalars are nullable because 0, false
# and '' are real answers from XYP; null is the only honest way to say "absent".
_SCALARS = {
    "string": ("?string", "string|null"),
    "int": ("?int", "int|null"),
    "float": ("?float", "float|null"),
    "bool": ("?bool", "bool|null"),
    "decimal": ("?string", "string|null"),
    "bytes": ("?string", "string|null"),
}
# The phpdoc type of one list item, for the kinds a list item has the same type in
# both directions.
_ITEM_DOC = {
    "string": "string",
    "int": "int",
    "float": "float",
    "bool": "bool",
    "decimal": "string",
    "any": "mixed",
}
# Scalars the decoder cannot tell from their PHP type alone.
_KIND_ATTRIBUTES = {
    "decimal": ("Decimal", _DECIMAL_ATTRIBUTE),
    "bytes": ("Bytes", _BYTES_ATTRIBUTE),
}


@dataclass(frozen=True)
class PropertyView:
    name: str  # PHP property (and named argument) name
    wire_name: str
    native_type: str
    doc_type: str
    default: str
    attributes: tuple[str, ...]  # attribute bodies, e.g. "ListOf('string')"
    imports: frozenset[str]
    doc: str

    @property
    def param_tag(self) -> str:
        tag = f"@param {self.doc_type} ${self.name}"
        return f"{tag} {self.doc}" if self.doc else tag


@dataclass(frozen=True)
class ClassView:
    name: str
    doc: tuple[str, ...]  # docblock lines, "" for a blank one
    properties: tuple[PropertyView, ...]

    @property
    def imports(self) -> tuple[str, ...]:
        return _sorted_imports(name for item in self.properties for name in item.imports)


@dataclass(frozen=True)
class OperationView:
    method: str  # e.g. "getCitizenIDCardInfo"
    operation: str
    doc: tuple[str, ...]
    params: ClassView
    classes: tuple[ClassView, ...]  # nested first, the response last
    response: str | None
    accepts_auth: bool

    @property
    def class_names(self) -> tuple[str, ...]:
        return tuple(sorted([self.params.name, *(item.name for item in self.classes)]))


@dataclass(frozen=True)
class GroupView:
    name: str  # "labor_welfare"
    client_property: str  # "laborWelfare"
    namespace: str  # "LaborWelfare"
    endpoints: tuple[str, ...]
    operations: tuple[OperationView, ...]

    @property
    def service(self) -> str:
        return f"{self.namespace}Service"

    @property
    def summary(self) -> str:
        count = len(self.operations)
        noun = "service" if count == 1 else "services"
        endpoints = ", ".join(self.endpoints)
        return f"The {count} XYP {noun} of the `{self.name}` group, served from {endpoints}."

    @property
    def doc(self) -> tuple[str, ...]:
        return (
            self.summary,
            "",
            f"Reached through `$xyp->{self.client_property}`; every method sends one request "
            "through that XypClient.",
        )

    @property
    def imports(self) -> tuple[str, ...]:
        auth = (_AUTH,) if any(item.accepts_auth for item in self.operations) else ()
        return _sorted_imports((_CLIENT, *auth))


def _doc(text: str) -> str:
    """One line that cannot end the docblock it sits in."""
    return " ".join(text.replace("*/", "* /").split())


def _sentence(text: str) -> str:
    return text if text.endswith(_SENTENCE_END) else f"{text}."


def _summary(prefix: str, service: Service) -> tuple[str, ...]:
    """'Input of WS…: what it does.' plus the provider, as docblock lines."""
    doc = _doc(service.doc)
    lines = (
        _sentence(
            f"{prefix} {service.operation}: {doc}" if doc else f"{prefix} {service.operation}"
        ),
    )
    organization = _doc(service.organization)
    return (*lines, "", f"Provider: {organization}") if organization else lines


def php_string(value: str) -> str:
    """A single-quoted PHP string literal."""
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _sorted_imports(names: Iterable[str]) -> tuple[str, ...]:
    """php-cs-fixer's `ordered_imports` alpha order: case-insensitive, `\\` as a space."""
    return tuple(sorted(set(names), key=lambda name: name.replace("\\", " ").lower()))


def _wire_attribute(name: str, wire_name: str) -> tuple[tuple[str, ...], frozenset[str]]:
    if name == wire_name:
        return (), frozenset()
    return (f"Wire({php_string(wire_name)})",), frozenset({_WIRE_ATTRIBUTE})


def _input_item_doc(type_ref: TypeRef) -> str:
    if type_ref.kind == "list":
        raise ValueError("A list of lists has no PHP mapping in the design contract")
    if type_ref.kind == "object":
        return "array<string, mixed>"
    if type_ref.kind == "date":
        return "\\DateTimeInterface|string"
    if type_ref.kind == "bytes":
        # Spelled out: `Bytes` is the attribute's short name in these files.
        return "\\Xyp\\Bytes"
    return _ITEM_DOC[type_ref.kind]


def _input_property(field: Field) -> PropertyView:
    """Inputs are plain PHP values; the encoder reads their runtime type."""
    name = property_name(field.wire_name)
    attributes, imports = _wire_attribute(name, field.wire_name)
    kind = field.type.kind
    default = "null"
    if kind == "list" and field.type.item:
        native, doc_type, default = "array", f"list<{_input_item_doc(field.type.item)}>", "[]"
    elif kind == "object":
        native, doc_type = "?array", "array<string, mixed>|null"
    elif kind == "date":
        native = doc_type = "\\DateTimeInterface|string|null"
    elif kind == "any":
        native = doc_type = "mixed"
    else:
        native, doc_type = _SCALARS[kind]
        if kind in _KIND_ATTRIBUTES:
            attribute, import_name = _KIND_ATTRIBUTES[kind]
            attributes, imports = (attribute, *attributes), imports | {import_name}
    return PropertyView(
        name, field.wire_name, native, doc_type, default, attributes, imports, _doc(field.doc)
    )


def _output_item(type_ref: TypeRef, nested: str) -> tuple[str, str, frozenset[str]]:
    """(#[ListOf] argument, phpdoc item type, imports) for one list item."""
    kind = type_ref.kind
    if kind == "list":
        raise ValueError("A list of lists has no PHP mapping in the design contract")
    if kind == "object":
        return f"{nested}::class", nested, frozenset()
    if kind == "date":
        return php_string(kind), "Date", frozenset({_DATE})
    if kind == "bytes":
        return php_string(kind), "string", frozenset()
    return php_string(kind), _ITEM_DOC[kind], frozenset()


def _output_property(field: Field, nested: str, taken: frozenset[str]) -> PropertyView:
    """`nested` names the class of an object (or of a list's objects)."""
    name = property_name(field.wire_name, taken)
    kind = field.type.kind
    attributes: tuple[str, ...] = ()
    imports: frozenset[str] = frozenset()
    default = "null"
    if kind == "list" and field.type.item:
        list_of, item_doc, imports = _output_item(field.type.item, nested)
        attributes, imports = (f"ListOf({list_of})",), imports | {_LIST_OF_ATTRIBUTE}
        native, doc_type, default = "array", f"list<{item_doc}>", "[]"
    elif kind == "object":
        native, doc_type = f"?{nested}", f"{nested}|null"
    elif kind == "date":
        native, doc_type, imports = "?Date", "Date|null", frozenset({_DATE})
    elif kind == "any":
        native = doc_type = "mixed"
    else:
        native, doc_type = _SCALARS[kind]
        if kind in _KIND_ATTRIBUTES:
            attribute, import_name = _KIND_ATTRIBUTES[kind]
            attributes, imports = (attribute,), frozenset({import_name})
    wire, wire_imports = _wire_attribute(name, field.wire_name)
    return PropertyView(
        name,
        field.wire_name,
        native,
        doc_type,
        default,
        (*attributes, *wire),
        imports | wire_imports,
        _doc(field.doc),
    )


_EXTRAS_VIEW = PropertyView(
    name=_EXTRAS_PROPERTY,
    wire_name="",
    native_type="Extras",
    doc_type="Extras",
    default="new Extras()",
    attributes=(),
    imports=frozenset({_EXTRAS}),
    doc="What this class could not hold: ->mismatches lists the response fields that did "
    "not fit (they kept their default), ->raw is the whole response tree.",
)


def _holds_object(type_ref: TypeRef) -> bool:
    item = type_ref.item if type_ref.kind == "list" else type_ref
    return item is not None and item.kind == "object"


def _classes_for(
    name: str,
    doc: tuple[str, ...],
    fields: tuple[Field, ...],
    context: tuple[str, str],
    taken: frozenset[str] = frozenset(),
) -> tuple[ClassView, ...]:
    """Depth-first, nested classes before the ones that use them. `context` is the
    operation and the wire path of `fields`, for the nested classes' docblocks."""
    operation, path = context
    nested: tuple[ClassView, ...] = ()
    properties: tuple[PropertyView, ...] = ()
    for field in fields:
        child = f"{name}{class_part(field.wire_name)}"
        if field.children or _holds_object(field.type):
            child_path = f"{path}.{field.wire_name}" if path else field.wire_name
            child_doc = _doc(field.doc)
            where = f"`{child_path}` in the response of {operation}."
            child_lines = (child_doc, "", where) if child_doc else (where,)
            nested = (
                *nested,
                *_classes_for(child, child_lines, field.children, (operation, child_path)),
            )
        properties = (*properties, _output_property(field, child, taken))
    view = ClassView(name, doc, properties)
    _require_unique_properties(view)
    return (*nested, view)


def _require_unique_properties(view: ClassView) -> None:
    """Two wire names can end up as one PHP name ('this' next to 'this_'). No rule can
    pick a winner, so the generator stops and the catalog gets looked at. Exact
    comparison: PHP property names, unlike class and method names, are case-sensitive."""
    _require_unique(f"PHP class {view.name!r}", "properties", [p.name for p in view.properties])


def _response_classes(service: Service, base: str) -> tuple[ClassView, ...]:
    *nested, root = _classes_for(
        base, (), service.outputs, (service.operation, ""), frozenset({_EXTRAS_PROPERTY})
    )
    response = ClassView(
        f"{base}Response", _summary("Response of", service), (*root.properties, _EXTRAS_VIEW)
    )
    _require_unique_properties(response)
    return (*nested, response)


def _params_class(service: Service, base: str) -> ClassView:
    properties = tuple(_input_property(field) for field in service.inputs)
    note = (
        "Every field is optional: null, '' and [] are left out of the request."
        if properties
        else "The operation takes no input fields."
    )
    view = ClassView(f"{base}Params", (*_summary("Input of", service), "", note), properties)
    _require_unique_properties(view)
    return view


def _method_doc(service: Service, has_response: bool) -> tuple[str, ...]:
    lines = _summary("Calls", service)
    if not has_response:
        lines = (
            *lines,
            "",
            "XYP publishes no response fields for this operation, so this returns the "
            "response tree as XypClient::call() does.",
        )
    if not service.accepts_auth:
        lines = (*lines, "", "The operation's request has no <auth> element, so it takes none.")
    return (*lines, "", _THROWS)


def _operation_view(service: Service, method: str, base: str) -> OperationView:
    classes = _response_classes(service, base) if service.outputs else ()
    response = f"{base}Response" if service.outputs else None
    return OperationView(
        method=method,
        operation=service.operation,
        doc=_method_doc(service, response is not None),
        params=_params_class(service, base),
        classes=classes,
        response=response,
        accepts_auth=service.accepts_auth,
    )


def _group_view(group: str, services: tuple[Service, ...]) -> GroupView:
    """Names only have to be unique inside the group's namespace (classes) and its
    service class (methods). Both are case-insensitive in PHP, so compared lowercased."""
    namespace = group_namespace(group)
    operations: tuple[OperationView, ...] = ()
    for service in services:
        code, short = split_operation(service.operation)
        taken: set[str] = {operation.method.lower() for operation in operations}
        method = method_name(short)
        method = f"{method}{code}" if method.lower() in taken else method
        base = upper_first(method)
        view = _operation_view(service, method, base)
        used = {f"{namespace}Service".lower()} | {
            item.lower() for operation in operations for item in operation.class_names
        }
        if used & {item.lower() for item in view.class_names} and not base.endswith(code):
            # The same service published twice: keep the method name, qualify the classes.
            view = _operation_view(service, method, f"{base}{code}")
        operations = (*operations, view)

    group_view = GroupView(
        name=group,
        client_property=group_property(group),
        namespace=namespace,
        endpoints=tuple(sorted({service.endpoint for service in services})),
        operations=operations,
    )
    _require_unique_names(group_view)
    return group_view


def _require_unique_names(group: GroupView) -> None:
    namespace = f"{ROOT_NAMESPACE}\\{group.namespace}"
    methods = [operation.method for operation in group.operations]
    classes = [group.service, *(name for op in group.operations for name in op.class_names)]
    _require_unique(f"PHP class {group.service!r}", "methods", methods, fold_case=True)
    _require_unique(f"PHP namespace {namespace!r}", "classes", classes, fold_case=True)
    unusable = sorted(
        name for name in classes if name.lower() in RESERVED_CLASS_NAMES | _IMPORTED_NAMES
    )
    if unusable:
        raise ValueError(
            f"PHP namespace {namespace!r} would declare classes whose names are reserved "
            f"or imported by the generated files: {unusable}"
        )


def _require_unique(
    owner: str, kind: str, names: Sequence[str], *, fold_case: bool = False
) -> None:
    keys = [name.lower() if fold_case else name for name in names]
    duplicates = sorted(
        {name for name, key in zip(names, keys, strict=True) if keys.count(key) > 1}
    )
    if duplicates:
        note = " (compared case-insensitively, as PHP does)" if fold_case else ""
        raise ValueError(f"{owner} would declare these {kind} twice{note}: {duplicates}")


def _group_views(api: Api) -> tuple[GroupView, ...]:
    groups = tuple(_group_view(name, services) for name, services in api.groups.items())
    _require_unique(
        "PHP namespace 'Xyp'", "group namespaces", [g.namespace for g in groups], fold_case=True
    )
    _require_unique("PHP trait 'ServiceGroups'", "properties", [g.client_property for g in groups])
    return groups


def docblock(lines: Sequence[str], indent: int = 0) -> str:
    pad = " " * indent
    body = [f"{pad} * {line}" if line else f"{pad} *" for line in lines]
    return "\n".join([f"{pad}/**", *body, f"{pad} */"])


def emit(api: Api, package_dir: Path) -> list[Path]:
    """Write every generated class into `package_dir`/src (…/packages/php/src) and
    format them with the package's php-cs-fixer config."""
    environment = Environment(
        loader=PackageLoader("xyp_generator.php", "templates"),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )
    environment.filters["phpstr"] = php_string
    environment.filters["docblock"] = docblock

    def render(template: str, **context: object) -> str:
        template_context = {"preamble": PREAMBLE, "root": ROOT_NAMESPACE, **context}
        return environment.get_template(template).render(**template_context)

    source = package_dir / "src"
    groups = _group_views(api)
    outputs: tuple[tuple[Path, str], ...] = (
        (source / "Registry.php", render("registry.php.j2", api=api)),
        (source / "ServiceGroups.php", render("service_groups.php.j2", groups=groups)),
    )
    for group in groups:
        directory = source / group.namespace
        classes = (
            view
            for operation in group.operations
            for view in (operation.params, *operation.classes)
        )
        outputs = (
            *outputs,
            (directory / f"{group.service}.php", render("service.php.j2", group=group)),
            *(
                (directory / f"{view.name}.php", render("class.php.j2", group=group, view=view))
                for view in classes
            ),
        )
    paths = [path for path, _ in outputs]
    _require_unique_paths(paths)
    _require_generated(source, [path for path in paths if path.parent == source])
    _require_generated_groups(source, [source / group.namespace for group in groups])

    _remove_stale_groups(source)
    for path, content in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    _format(
        package_dir,
        ["src/Registry.php", "src/ServiceGroups.php", *(f"src/{g.namespace}" for g in groups)],
    )
    return paths


def _require_unique_paths(paths: list[Path]) -> None:
    """Lowercased: on a case-insensitive disk (macOS, Windows) two such files are one."""
    _require_unique("The PHP generator", "files", [str(path) for path in paths], fold_case=True)


def _is_generated(path: Path) -> bool:
    with path.open(encoding="utf-8") as handle:
        head = [handle.readline().rstrip("\n") for _ in range(_HEADER_LINES)]
    return HEADER in head


def _require_generated(source: Path, files: list[Path]) -> None:
    """Never overwrite a hand-written file."""
    for path in files:
        if path.exists() and not _is_generated(path):
            raise ValueError(f"{path} exists and was not written by xyp-generator")


def _service_file(directory: Path) -> Path:
    return directory / f"{directory.name}Service.php"


def _require_generated_groups(source: Path, directories: list[Path]) -> None:
    """A group whose directory is hand-written (`Http`, `Exception`) would mix with it."""
    for directory in directories:
        if directory.exists() and not (
            _service_file(directory).is_file() and _is_generated(_service_file(directory))
        ):
            raise ValueError(f"{directory} exists and was not written by xyp-generator")


def _remove_stale_groups(source: Path) -> None:
    """Drop the group directories of a previous run, so a group or operation XYP removed
    does not linger. A directory without a generated <Name>Service.php is never touched."""
    if not source.is_dir():
        return
    for directory in sorted(source.iterdir()):
        service = _service_file(directory)
        if directory.is_dir() and service.is_file() and _is_generated(service):
            shutil.rmtree(directory)


def _format(package_dir: Path, paths: list[str]) -> None:
    """A safety net: the templates already produce PER-CS 2.0 code, and CI checks the
    package with the same config."""
    # composer.json lives at the repository root (Packagist reads it from there),
    # so that is where the dev tools are installed.
    repo_root = package_dir.resolve().parents[1]
    fixer = repo_root / "vendor" / "bin" / "php-cs-fixer"
    if not fixer.is_file():
        raise FileNotFoundError(f"{fixer} is missing: run `composer install` in {repo_root}")
    command = [str(fixer.resolve()), "fix", "--config=.php-cs-fixer.dist.php", "--", *paths]
    subprocess.run(command, cwd=package_dir, check=True, capture_output=True)
