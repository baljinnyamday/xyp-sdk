"""Render the Go SDK's generated packages from the IR."""

from __future__ import annotations

import json
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

from jinja2 import Environment, PackageLoader, StrictUndefined

from xyp_generator.go.names import go_field_name, go_package_name, upper_first
from xyp_generator.ir import Api, Field, Service, TypeRef
from xyp_generator.naming import snake_case, split_operation

# The exact wording `go` tools look for, so editors, linters and reviewers all
# recognise these files as generated.
HEADER = "// Code generated by xyp-generator from spec/services.json. DO NOT EDIT."

XYP_IMPORT = "github.com/baljinnyamday/xyp-sdk/packages/go/xyp"

# Same Go types on the way in and on the way out. The optional scalars are
# pointers because 0 and false are real answers from XYP, so nil is the only
# honest way to say "absent"; a string is not, because XML cannot tell an empty
# string from a missing element.
_SCALARS = {
    "string": "string",
    "int": "*int64",
    "float": "*float64",
    "bool": "*bool",
    "decimal": "xyp.Decimal",
    "bytes": "[]byte",
    "date": "xyp.Date",
    "any": "any",
}
_EXTRAS_FIELD = "Xyp"


@dataclass(frozen=True)
class FieldView:
    name: str
    wire_name: str
    type: str
    doc: str


@dataclass(frozen=True)
class StructView:
    name: str
    doc: str
    fields: tuple[FieldView, ...]


@dataclass(frozen=True)
class OperationView:
    name: str  # method name, e.g. "GetCitizenIDCardInfo"
    file_name: str
    operation: str
    doc: str
    organization: str
    params: StructView
    structs: tuple[StructView, ...]  # nested first, the response last
    response: str | None
    accepts_auth: bool

    @property
    def type_names(self) -> tuple[str, ...]:
        return tuple(sorted([self.params.name, *(struct.name for struct in self.structs)]))

    @property
    def uses_xyp(self) -> bool:
        """gofmt neither adds nor removes imports, so the template has to get this
        right. Every operation imports `context`; only some of them name an xyp type."""
        types = [field.type for struct in (self.params, *self.structs) for field in struct.fields]
        return (
            self.accepts_auth or self.response is not None or any("xyp." in name for name in types)
        )


@dataclass(frozen=True)
class GroupView:
    name: str  # "labor_welfare"
    package: str  # "laborwelfare"
    endpoints: tuple[str, ...]
    operations: tuple[OperationView, ...]


def _doc(text: str) -> str:
    """One line, so it fits a `//` comment."""
    return " ".join(text.split())


def _output_type(type_ref: TypeRef, nested: str) -> str:
    if type_ref.kind == "list" and type_ref.item:
        item = type_ref.item
        # A list item is a value, not a pointer: a list has no absent items.
        return f"[]{nested}" if item.kind == "object" else f"[]{_output_type(item, nested)}"
    if type_ref.kind == "object":
        return f"*{nested}"
    return _SCALARS[type_ref.kind]


def _input_type(type_ref: TypeRef) -> str:
    if type_ref.kind == "list" and type_ref.item:
        return f"[]{_input_type(type_ref.item)}"
    if type_ref.kind == "object":
        return "map[string]any"
    return _SCALARS[type_ref.kind]


def _field_views(fields: tuple[Field, ...], types: tuple[str, ...]) -> tuple[FieldView, ...]:
    return tuple(
        FieldView(
            name=go_field_name(field.wire_name),
            wire_name=field.wire_name,
            type=field_type,
            doc=_doc(field.doc),
        )
        for field, field_type in zip(fields, types, strict=True)
    )


def _require_unique_fields(struct: str, fields: tuple[FieldView, ...]) -> None:
    """Two wire names can spell the same Go name ('civil_id' and 'civilId'). No rule
    can pick a winner, so the generator stops and the catalog gets looked at."""
    names = [field.name for field in fields]
    duplicates = sorted({name for name in names if names.count(name) > 1})
    if duplicates:
        raise ValueError(f"Go struct {struct!r} would declare these fields twice: {duplicates}")


def _structs_for(name: str, doc: str, fields: tuple[Field, ...]) -> tuple[StructView, ...]:
    """Depth-first, nested structs before the ones that use them."""
    nested: tuple[StructView, ...] = ()
    types: tuple[str, ...] = ()
    for field in fields:
        child = f"{name}{go_field_name(field.wire_name)}"
        if field.children:
            nested = (*nested, *_structs_for(child, field.doc, field.children))
        types = (*types, _output_type(field.type, child))
    views = _field_views(fields, types)
    _require_unique_fields(name, views)
    return (*nested, StructView(name=name, doc=_doc(doc), fields=views))


def _response_struct(service: Service, base: str) -> tuple[StructView, ...]:
    *nested, root = _structs_for(base, "", service.outputs)
    if any(field.name == _EXTRAS_FIELD for field in root.fields):
        raise ValueError(
            f"{service.operation} has a response field named {_EXTRAS_FIELD!r}, "
            "which the generated response struct already uses for xyp.Extras"
        )
    return (*nested, StructView(f"{base}Response", _doc(service.doc), root.fields))


def _operation_view(service: Service, name: str, base: str) -> OperationView:
    code, short = split_operation(service.operation)
    structs = _response_struct(service, base) if service.outputs else ()
    params = StructView(
        name=f"{base}Params",
        doc="",
        fields=_field_views(
            service.inputs, tuple(_input_type(field.type) for field in service.inputs)
        ),
    )
    _require_unique_fields(params.name, params.fields)
    return OperationView(
        name=name,
        # The code suffix is always there on purpose: it keeps a file from ever
        # ending in `_test.go` or in a `_GOOS`/`_GOARCH` suffix Go would read as a
        # build constraint, and it rules out collisions on case-insensitive disks.
        file_name=f"{snake_case(short)}_{code.lower()}.go",
        operation=service.operation,
        doc=_doc(service.doc),
        organization=_doc(service.organization),
        params=params,
        structs=structs,
        response=f"{base}Response" if service.outputs else None,
        accepts_auth=service.accepts_auth,
    )


def _group_view(group: str, services: tuple[Service, ...]) -> GroupView:
    """Names only have to be unique inside the group's package, which is the only
    place they are visible."""
    operations: tuple[OperationView, ...] = ()
    for service in services:
        code, short = split_operation(service.operation)
        # Compared case-insensitively: Go method names must also be unique to a reader.
        taken = {operation.name.lower() for operation in operations}
        name = upper_first(short)
        name = f"{name}{code}" if name.lower() in taken else name
        view = _operation_view(service, name, name)
        used = {item for operation in operations for item in operation.type_names}
        if used & set(view.type_names):
            # The same service published twice: keep the method name, qualify the types.
            view = _operation_view(service, name, f"{name}{code}")
        operations = (*operations, view)

    _require_unique(group, operations)
    return GroupView(
        name=group,
        package=go_package_name(group),
        endpoints=tuple(sorted({service.endpoint for service in services})),
        operations=operations,
    )


def _require_unique(group: str, operations: tuple[OperationView, ...]) -> None:
    package = go_package_name(group)
    methods = [operation.name for operation in operations]
    types = [name for operation in operations for name in operation.type_names]
    for kind, names in (("methods", methods), ("types", types)):
        duplicates = sorted({name for name in names if names.count(name) > 1})
        if duplicates:
            raise ValueError(
                f"Go package {package!r} would declare these {kind} twice: {duplicates}"
            )


def emit(api: Api, package_dir: Path) -> list[Path]:
    """Write every generated file into `package_dir` (…/packages/go) and format them."""
    environment = Environment(
        loader=PackageLoader("xyp_generator.go", "templates"),
        undefined=StrictUndefined,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
    )
    environment.filters["gostr"] = lambda value: json.dumps(value, ensure_ascii=False)

    def render(template: str, **context: object) -> str:
        template_context = {"header": HEADER, "xyp_import": XYP_IMPORT, **context}
        return environment.get_template(template).render(**template_context)

    source = package_dir / "xyp"
    groups = _group_views(api)
    outputs: tuple[tuple[Path, str], ...] = (
        (source / "registry.go", render("registry.go.j2", api=api)),
    )
    for group in groups:
        directory = source / group.package
        outputs = (
            *outputs,
            (directory / "service.go", render("service.go.j2", group=group)),
            *(
                (
                    directory / operation.file_name,
                    render("operation.go.j2", group=group, operation=operation),
                )
                for operation in group.operations
            ),
        )
    paths = [path for path, _ in outputs]
    _require_unique_paths(paths)

    _remove_stale_packages(source)
    for path, content in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    _format(source)
    return paths


def _group_views(api: Api) -> tuple[GroupView, ...]:
    return tuple(_group_view(name, services) for name, services in api.groups.items())


def _require_unique_paths(paths: list[Path]) -> None:
    duplicates = sorted({str(path) for path in paths if paths.count(path) > 1})
    if duplicates:
        raise ValueError(f"These Go files would be written twice: {duplicates}")


def _remove_stale_packages(source: Path) -> None:
    """Drop the group packages of a previous run, so a group XYP removed does not
    linger. `certs` and `testdata` hold no service.go and are never touched."""
    for directory in sorted(source.iterdir()):
        service = directory / "service.go"
        if not directory.is_dir() or not service.is_file():
            continue
        if service.read_text(encoding="utf-8").startswith(HEADER):
            shutil.rmtree(directory)


def _format(source: Path) -> None:
    # gofmt is the only formatter Go has, and CI checks that `gofmt -l` is empty.
    subprocess.run(["gofmt", "-w", str(source)], check=True, capture_output=True)
