from __future__ import annotations

import pytest

from xyp_generator.go.emit import HEADER, FieldView, _require_unique_fields
from xyp_generator.go.names import go_field_name, go_package_name, upper_first


@pytest.mark.parametrize(
    ("wire_name", "expected"),
    [
        ("created_date", "CreatedDate"),
        ("civilId", "CivilId"),  # XYP's own spelling, not Go's CivilID
        ("regnum", "Regnum"),
        ("listAddress", "ListAddress"),
        ("ttv6_2_1", "Ttv621"),
        ("WSName", "WSName"),
        ("_private", "Private"),
        ("_", "X"),
    ],
)
def test_go_field_names(wire_name: str, expected: str) -> None:
    assert go_field_name(wire_name) == expected


def test_go_package_names_have_no_underscores() -> None:
    assert go_package_name("labor_welfare") == "laborwelfare"
    assert go_package_name("citizen") == "citizen"
    assert upper_first("getCitizenIDCardInfo") == "GetCitizenIDCardInfo"


def test_colliding_sibling_fields_stop_the_generator() -> None:
    fields = (
        FieldView("CivilId", "civil_id", "string", ""),
        FieldView("CivilId", "civilId", "string", ""),
    )
    with pytest.raises(ValueError, match="CivilId"):
        _require_unique_fields("Sample", fields)


def test_header_is_the_form_go_tools_recognise() -> None:
    # https://pkg.go.dev/cmd/go#hdr-Generate_Go_files_by_processing_source
    assert HEADER.startswith("// Code generated by ")
    assert HEADER.endswith(" DO NOT EDIT.")
